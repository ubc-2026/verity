import { createHash, timingSafeEqual } from "node:crypto";
import { DatabaseSync } from "node:sqlite";
import type { Hex } from "viem";
import { RESEARCH_RESOURCES, resourceByHash, resourceById } from "./catalog.ts";
import type { ReceiptSigner } from "./deliveryReceipt.ts";
import type { MerchantConfig, PaidRequest, SavedQuote } from "./merchant.ts";
import {
  deliverPaidRequest,
  MerchantDeliveryStore,
  type DeliveryResponse,
  type DeliverySettlementAdapter,
} from "./merchantDelivery.ts";
import { parseQuote, type VerityQuote } from "./quote.ts";
import { hashContent, parseResearchParameters, ResearchRequestError } from "./researchRequest.ts";

export interface QuoteRequest {
  catalogItemId: string;
  /** Generated by the buyer. The quote echoes it, and the buyer refuses a quote that does not. */
  purchaseId: string;
  parameters: unknown;
  catalogParameters?: Record<string, string>;
}

const PURCHASE_ID = /^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$/;

/** Durable quotes, so a retry after a merchant restart still verifies against the quote it paid for. */
class QuoteStore {
  readonly #db: DatabaseSync;
  constructor(path: string) {
    this.#db = new DatabaseSync(path);
    this.#db.exec("PRAGMA journal_mode = WAL");
    this.#db.exec(`CREATE TABLE IF NOT EXISTS merchant_quotes (
      quote_id    TEXT PRIMARY KEY,
      purchase_id TEXT NOT NULL UNIQUE,
      quote_json  TEXT NOT NULL
    ) STRICT;`);
  }
  get(quoteId: string): SavedQuote | undefined {
    const row = this.#db.prepare(`SELECT quote_json FROM merchant_quotes WHERE quote_id = ?`).get(quoteId) as
      | { quote_json: string }
      | undefined;
    if (!row) return undefined;
    const { buyerSessionId, ...wire } = JSON.parse(row.quote_json) as SavedQuote;
    return { ...parseQuote(wire), buyerSessionId };
  }
  insert(quote: SavedQuote): void {
    this.#db
      .prepare(`INSERT INTO merchant_quotes (quote_id, purchase_id, quote_json) VALUES (?, ?, ?)`)
      .run(quote.quoteId, quote.purchaseId, JSON.stringify(quote));
  }
  close() {
    this.#db.close();
  }
}

const sha256 = (value: string) => createHash("sha256").update(value, "utf8").digest();

/**
 * Demo merchant. It quotes allowlisted fixture documents to authenticated
 * buyer sessions, and every paid request goes through `deliverPaidRequest`:
 * binding check, one settlement per purchase, resume by tx hash, and a signed
 * DeliveryReceiptV1 over the exact bytes served.
 */
export class MerchantService {
  readonly deliveries: MerchantDeliveryStore;
  readonly #quotes: QuoteStore;
  readonly #config: MerchantConfig;
  readonly #signer: ReceiptSigner;
  readonly #settlement: DeliverySettlementAdapter;
  readonly #now: () => number;
  readonly #quoteTtlSeconds: number;
  readonly #sessions: { digest: Buffer; sessionId: string }[];
  readonly #artifact: (contentHash: Hex) => Uint8Array | undefined;

  constructor(options: {
    config: MerchantConfig;
    signer: ReceiptSigner;
    settlement: DeliverySettlementAdapter;
    now: () => number;
    /** Bearer token -> buyer session. Tokens are compared by SHA-256 digest in constant time. */
    sessions: Readonly<Record<string, string>>;
    /** SQLite path for quotes and deliveries. ":memory:" keeps both in memory (separate databases). */
    dbPath?: string;
    quoteTtlSeconds?: number;
    /** Overrides the bytes served for a content hash. Tests use it to simulate a merchant fault. */
    artifact?: (contentHash: Hex) => Uint8Array | undefined;
  }) {
    this.#config = options.config;
    this.#signer = options.signer;
    this.#settlement = options.settlement;
    this.#now = options.now;
    this.#quoteTtlSeconds = options.quoteTtlSeconds ?? 600;
    this.#sessions = Object.entries(options.sessions).map(([token, sessionId]) => ({ digest: sha256(token), sessionId }));
    this.#artifact = options.artifact ?? ((hash) => resourceByHash(hash)?.body);
    const path = options.dbPath ?? ":memory:";
    this.deliveries = new MerchantDeliveryStore(path);
    this.#quotes = new QuoteStore(path);
  }

  close() {
    this.deliveries.close();
    this.#quotes.close();
  }

  /** Buyer session for a bearer token, or undefined. */
  authenticate(token: string | undefined): string | undefined {
    if (!token) return undefined;
    const digest = sha256(token);
    let match: string | undefined;
    for (const session of this.#sessions) {
      if (timingSafeEqual(session.digest, digest)) match = session.sessionId;
    }
    return match;
  }

  listCatalog() {
    return RESEARCH_RESOURCES.map((resource) => ({
      catalogItemId: resource.item.catalogItemId,
      title: resource.title,
      price: resource.item.price.toString(10),
      resourceUrl: resource.item.resourceUrl,
      evidenceType: resource.item.evidenceType,
      requiredParameters: resource.item.requiredParameters,
      contentHash: hashContent(resource.body),
    }));
  }

  issueQuote(input: QuoteRequest, buyerSessionId: string): SavedQuote {
    const resource = resourceById(input.catalogItemId);
    if (!resource) throw new ResearchRequestError(`unknown catalog item: ${input.catalogItemId}`);
    if (resource.item.affects !== "resolution_risk") {
      throw new ResearchRequestError("this merchant does not sell outcome forecasts");
    }
    if (typeof input.purchaseId !== "string" || !PURCHASE_ID.test(input.purchaseId)) {
      throw new ResearchRequestError("purchaseId is missing or malformed");
    }
    const parameters = parseResearchParameters(input.parameters);
    if (parameters.evidenceType !== resource.item.evidenceType) {
      throw new ResearchRequestError("evidenceType does not match the catalog item");
    }

    const provided = input.catalogParameters ?? {};
    const keys = Object.keys(provided).sort();
    const required = [...resource.item.requiredParameters].sort();
    if (keys.join("|") !== required.join("|")) {
      throw new ResearchRequestError(`catalog parameters must be ${required.join(", ") || "(none)"}`);
    }
    for (const key of keys) {
      if (typeof provided[key] !== "string" || provided[key]!.length === 0) {
        throw new ResearchRequestError(`catalog parameter ${key} is empty`);
      }
    }
    if (resource.sampleParameters) {
      for (const [key, value] of Object.entries(resource.sampleParameters)) {
        if (provided[key] !== value) throw new ResearchRequestError(`no fixture document for ${key}=${provided[key]}`);
      }
    }

    const quoteId = `quote-${createHash("sha256").update(input.purchaseId).digest("hex").slice(0, 24)}`;
    if (this.#quotes.get(quoteId)) throw new ResearchRequestError(`quote already issued for purchase ${input.purchaseId}`);

    const quote = parseQuote({
      quoteId,
      purchaseId: input.purchaseId,
      merchantId: this.#config.merchantId,
      catalogItemId: resource.item.catalogItemId,
      method: "POST",
      resourceUrl: resource.item.resourceUrl,
      parameters,
      contentType: resource.item.contentType,
      expectedContentHash: hashContent(resource.body),
      chainId: this.#config.chainId,
      token: this.#config.token,
      payTo: this.#config.payTo,
      amount: resource.item.price.toString(10),
      expiresAt: this.#now() + this.#quoteTtlSeconds,
      ...(keys.length > 0 ? { catalogParameters: provided } : {}),
    });
    const saved: SavedQuote = { ...quote, buyerSessionId };
    this.#quotes.insert(saved);
    return saved;
  }

  /** The only paid path. Verification, settlement, and the receipt all happen inside deliverPaidRequest. */
  deliver(input: PaidRequest): Promise<DeliveryResponse> {
    return deliverPaidRequest(input, {
      config: this.#config,
      loadQuote: (quoteId) => this.#quotes.get(quoteId),
      hasArtifact: (contentHash) => resourceByHash(contentHash) !== undefined,
      now: this.#now,
      settlement: this.#settlement,
      deliveries: this.deliveries,
      loadArtifact: (contentHash) => this.#artifact(contentHash),
      receiptSigner: this.#signer,
    });
  }
}

export function savedQuoteWire(quote: SavedQuote): VerityQuote {
  const { buyerSessionId: _session, ...wire } = quote;
  return wire;
}
